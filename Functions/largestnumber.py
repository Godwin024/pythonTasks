def addition(first_number, second_number):

    sum_of_number = first_number + second_number

    return sum_of_number

def multiply (first_number, second_number):
    
    product_of_number = first_number * second_number
    
    return product_of_number

def substraction(first_number, second_number ):

    substract_number = first_number - second_number

    return substract_number
